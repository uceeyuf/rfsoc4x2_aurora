#!/usr/bin/env python3
# Generates rtl/prbs31_next.vh: the next W bits of PRBS31 (x^31 + x^28 + 1) from the last 31 bits.
# Word bit i is the sequence bit at time t0 + i (bit 0 the earliest); the state s[j] is word bit W - 31 + j of the
# previous word. Each next bit is the XOR of a fixed subset of the 31 state bits (b[n] = b[n - 31] ^ b[n - 28]).
#   python3 scripts/gen_prbs31.py [W]
# Copyright (c) 2026 Yijie Yu. BSD-3-Clause.
import os, sys

W = int(sys.argv[1]) if len(sys.argv) > 1 else 256
seq = [1 << j for j in range(31)]                 # masks of the previous word's last 31 bits
for n in range(W):
    seq.append(seq[n] ^ seq[n + 3])               # b[31 + n] = b[n] ^ b[n + 3]
masks = seq[31:]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "rtl", "prbs31_next.vh")
with open(out, "w") as f:
    f.write("// Generated by scripts/gen_prbs31.py: do not edit.\n")
    f.write(f"// The next {W} bits of PRBS31 (x^31 + x^28 + 1) from the previous word's last 31 bits s (s[0] the earliest);\n")
    f.write("// bit i of the result is the sequence bit at time t0 + i.\n")
    f.write(f"function [{W - 1}:0] prbs31_next(input [30:0] s);\n    begin\n")
    for i, m in enumerate(masks):
        f.write(f"        prbs31_next[{i}] = ^(s & 31'h{m:08x});\n")
    f.write("    end\nendfunction\n")
print(f"wrote {out}: {W} bits, at most {max(bin(m).count('1') for m in masks)} state bits each")
